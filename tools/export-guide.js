#!/usr/bin/env node
// Builds docs/USER-GUIDE.md from the help built into ConfigTool/index.html,
// so the GitHub guide and the in-page help never drift apart.
//
//   npm install playwright-core      (once; uses your installed Chrome)
//   node tools/export-guide.js
//
// Run it again whenever the help text in index.html changes.
const path = require('path');
const fs = require('fs');
const { chromium } = require('playwright-core');

const ROOT = path.resolve(__dirname, '..');
const PAGE = 'file://' + path.join(ROOT, 'ConfigTool', 'index.html');
const OUT = path.join(ROOT, 'docs', 'USER-GUIDE.md');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage();
  await page.goto(PAGE);
  const md = await page.evaluate(() => {
    // ---- tiny HTML -> GitHub Markdown converter for the help's markup ----
    const esc = (t) => t.replace(/\s+/g, ' ');
    function inline(n) {
      if (n.nodeType === 3) return esc(n.textContent);
      if (n.nodeType !== 1) return '';
      const kids = () => [...n.childNodes].map(inline).join('');
      switch (n.tagName) {
        case 'B': case 'STRONG': { const t = kids().trim(); return t ? `**${t}**` : ''; }
        case 'I': case 'EM': { const t = kids().trim(); return t ? `*${t}*` : ''; }
        case 'CODE': return '`' + n.textContent + '`';
        case 'KBD': return '<kbd>' + n.textContent + '</kbd>';
        case 'BR': return '  \n';
        case 'A': return kids();
        case 'SMALL': return ' (' + kids().trim() + ')';
        default: return kids();
      }
    }
    function table(t) {
      // bit-numbering grids: mark the signal's bits in bold
      const rows = [...t.querySelectorAll('tr')].map(tr => [...tr.children].map(c => {
        const v = inline(c).trim().replace(/\|/g, '\\|');
        return c.classList.contains('on') ? `**${v}**` : v;
      }));
      if (!rows.length) return '';
      const w = Math.max(...rows.map(r => r.length));
      const pad = (r) => [...r, ...Array(w - r.length).fill('')];
      const head = pad(rows[0]);
      return ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|', ...rows.slice(1).map(r => '| ' + pad(r).join(' | ') + ' |')].join('\n') + '\n\n';
    }
    function block(n, depth = 0) {
      if (n.nodeType === 3) { const t = esc(n.textContent).trim(); return t ? t + '\n\n' : ''; }
      if (n.nodeType !== 1) return '';
      const kids = () => [...n.childNodes].map(c => block(c, depth)).join('');
      if (n.classList.contains('help-diagram')) return '**' + [...n.children].map(c => c.classList.contains('hd-arrow') ? '⇄' : inline(c).trim()).join('  ') + '**\n\n';
      if (n.classList.contains('callout')) return inline(n).trim().split('\n').map(l => '> ' + l).join('\n') + '\n\n';
      switch (n.tagName) {
        case 'P': return inline(n).trim() + '\n\n';
        case 'H4': return '### ' + inline(n).trim() + '\n\n';
        case 'UL': case 'OL': {
          let i = 0;
          return [...n.children].map(li => {
            const lead = '  '.repeat(depth) + (n.tagName === 'OL' ? `${++i}. ` : '- ');
            const sub = [...li.children].filter(c => c.tagName === 'UL' || c.tagName === 'OL');
            const text = [...li.childNodes].filter(c => !sub.includes(c)).map(inline).join('').trim();
            return lead + text + '\n' + sub.map(s => block(s, depth + 1)).join('');
          }).join('') + (depth ? '' : '\n');
        }
        case 'TABLE': return table(n);
        case 'DL': return [...n.children].map(c => c.tagName === 'DT' ? `**${inline(c).trim()}**  \n` : inline(c).trim() + '\n\n').join('');
        case 'DIV': case 'SECTION': return kids();
        default: return inline(n).trim() ? inline(n).trim() + '\n\n' : '';
      }
    }
    const slug = (t) => t.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');   // GitHub's anchor rule
    const groups = [];
    for (const s of HELP) { let g = groups.find(x => x.name === s.group); if (!g) groups.push(g = { name: s.group, items: [] }); g.items.push(s); }
    const ORDER = ['Basics', 'Tabs', 'How to', 'Reference'];
    groups.sort((x, y) => (ORDER.indexOf(x.name) + 99) % 99 - (ORDER.indexOf(y.name) + 99) % 99);
    let out = '<!-- Generated by tools/export-guide.js from the help in ConfigTool/index.html. Edit the help there, then re-run the script. -->\n\n';
    out += '# CAN Isolator — User guide\n\nThis is the same help that is built into the config tool (press <kbd>?</kbd> on any tab). It is generated from the page, so the two always match.\n\n## Contents\n\n';
    for (const g of groups) out += `**${g.name}:** ` + g.items.map(s => `[${s.title}](#${slug(s.title)})`).join(' · ') + '\n\n';
    for (const g of groups) {
      for (const s of g.items) {
        const div = document.createElement('div');
        div.innerHTML = s.html;
        out += `## ${s.title}\n\n` + block(div).replace(/\n{3,}/g, '\n\n') + '\n';
      }
    }
    return out.replace(/[ \t]+\n/g, (m) => m.endsWith('  \n') ? '  \n' : '\n');
  });
  fs.writeFileSync(OUT, md);
  console.log('wrote', path.relative(ROOT, OUT), md.length, 'bytes');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
